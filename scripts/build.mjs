// Builds build/generated.mjs (inlined HTML + images for the Worker) and static previews.
import {readFileSync,writeFileSync,mkdirSync,readdirSync,cpSync,rmSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=join(dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>readFileSync(join(root,p));
const out=join(root,'build');rmSync(out,{recursive:true,force:true});mkdirSync(out,{recursive:true});

// Assets served under /app/assets/
const assets={};
for(const f of readdirSync(join(root,'assets/icons')).sort())assets['icons/'+f]=read('assets/icons/'+f);
for(const f of readdirSync(join(root,'assets/pwa')).sort())assets['pwa/'+f]=read('assets/pwa/'+f);
assets['decoration-cat.png']=read('assets/decoration-cat.png');

// Notion widget (unchanged behaviour): demo icons are inlined as data URLs, as before.
const koNames=['지갑','계산기','달력','집','고지서','숟가락_젓가락','책과_필기구','버스','쇼핑백','통장','지폐','돈봉투','구독료_노트북','결산차트','캐리어','저금통','색조화장품','스마트폰','장바구니','청진기와_주사기','사료그릇','신용카드','뜨개질','옷과_구두','영화티켓','자동차','책','세제와_휴지','치킨박스'];
const iconFiles=Object.keys(assets).filter(k=>k.startsWith('icons/'));
const demoIcons=iconFiles.map((k,i)=>({id:'demo-icon-'+i,name:koNames[i],url:'data:image/png;base64,'+assets[k].toString('base64')}));
const widgetHtml=read('widget/widget.html').toString().replace('/*__DEMO_ICONS__*/[]',JSON.stringify(demoIcons));

const appHtml=read('app/app.html').toString();
const manifest=read('app/manifest.webmanifest').toString();
const version=createHash('sha256').update(appHtml).update(manifest).update(read('app/sw.js')).update(JSON.stringify(Object.keys(assets))).digest('hex').slice(0,12);
const sw=read('app/sw.js').toString().replace('__BUILD_VERSION__',version).replace("'__ASSET_LIST__'",JSON.stringify(Object.keys(assets).map(k=>'assets/'+k)));

const b64=Object.fromEntries(Object.entries(assets).map(([k,v])=>['/app/assets/'+k,v.toString('base64')]));
writeFileSync(join(out,'generated.mjs'),
  '// Generated by scripts/build.mjs. Do not edit.\n'+
  'export const VERSION='+JSON.stringify(version)+';\n'+
  'export const WIDGET_HTML='+JSON.stringify(widgetHtml)+';\n'+
  'export const APP_HTML='+JSON.stringify(appHtml)+';\n'+
  'export const MANIFEST='+JSON.stringify(manifest)+';\n'+
  'export const SW='+JSON.stringify(sw)+';\n'+
  'export const ASSETS='+JSON.stringify(b64)+';\n');

// Static previews (open in a browser; demo data only)
writeFileSync(join(out,'widget-preview.html'),widgetHtml);
const appDir=join(out,'app-preview');mkdirSync(appDir,{recursive:true});
writeFileSync(join(appDir,'index.html'),appHtml);
cpSync(join(root,'assets'),join(appDir,'assets'),{recursive:true});
console.log('Built version',version,'-',Object.keys(assets).length,'assets');
